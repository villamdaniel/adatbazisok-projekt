CREATE TABLE korterem (
    korterem_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    osztaly_id integer NOT NULL
        REFERENCES osztaly (osztaly_id) ON DELETE RESTRICT,
    szam varchar(10) NOT NULL,
    UNIQUE (osztaly_id, szam)
);

CREATE TABLE agy (
    agy_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    korterem_id integer NOT NULL
        REFERENCES korterem (korterem_id) ON DELETE RESTRICT,
    agy_szam smallint NOT NULL CHECK (agy_szam > 0),
    statusz text NOT NULL DEFAULT 'szabad'
        CHECK (statusz IN ('szabad', 'foglalt', 'karbantartas')),
    UNIQUE (korterem_id, agy_szam)
);

-- ---------------------------------------------------------------------------
-- Betegek és ellátás
