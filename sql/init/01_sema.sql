CREATE TABLE osztaly (
    osztaly_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kod varchar(8) NOT NULL UNIQUE,
    nev text NOT NULL UNIQUE,
    epulet varchar(20) NOT NULL,
    emelet smallint NOT NULL CHECK (emelet BETWEEN 0 AND 20),
    vezeto_orvos_id integer,
    leiras text
);

CREATE TABLE alkalmazott (
    alkalmazott_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vezeteknev text NOT NULL,
    keresztnev text NOT NULL,
    szuletesi_datum date NOT NULL CHECK (szuletesi_datum >= DATE '1940-01-01'),
    email dom_email NOT NULL UNIQUE,
    telefon varchar(20),
    felvetel_datuma date NOT NULL,
    aktiv boolean NOT NULL DEFAULT true,
    CONSTRAINT ck_alkalmazott_felnott
        CHECK (felvetel_datuma >= (szuletesi_datum + INTERVAL '18 years')::date)
);

CREATE TABLE orvos (
    alkalmazott_id integer PRIMARY KEY
        REFERENCES alkalmazott (alkalmazott_id) ON DELETE RESTRICT,
    pecsetszam varchar(6) NOT NULL UNIQUE
        CONSTRAINT ck_pecsetszam CHECK (pecsetszam ~ '^[0-9]{5,6}$'),
    szakvizsga text NOT NULL,
    osztaly_id integer NOT NULL
        REFERENCES osztaly (osztaly_id) ON DELETE RESTRICT
);

CREATE TABLE apolo (
    alkalmazott_id integer PRIMARY KEY
        REFERENCES alkalmazott (alkalmazott_id) ON DELETE RESTRICT,
    oklevel_szam varchar(20) NOT NULL UNIQUE,
    osztaly_id integer NOT NULL
        REFERENCES osztaly (osztaly_id) ON DELETE RESTRICT
);

-- A vezető orvos csak az orvos tábla létrejötte után hivatkozható.
ALTER TABLE osztaly
    ADD CONSTRAINT fk_osztaly_vezeto
    FOREIGN KEY (vezeto_orvos_id) REFERENCES orvos (alkalmazott_id)
    ON DELETE SET NULL;

