CREATE TABLE beteg (
    beteg_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    taj_szam dom_taj NOT NULL UNIQUE,
    vezeteknev text NOT NULL,
    keresztnev text NOT NULL,
    szuletesi_datum date NOT NULL CHECK (szuletesi_datum >= DATE '1900-01-01'),
    nem text NOT NULL CHECK (nem IN ('ferfi', 'no')),
    email dom_email UNIQUE,
    telefon varchar(20),
    iranyitoszam varchar(4) CHECK (iranyitoszam ~ '^[0-9]{4}$'),
    varos text,
    utca text,
    regisztracio_datuma date NOT NULL DEFAULT CURRENT_DATE
);

CREATE TABLE diagnozis (
    kod varchar(8) PRIMARY KEY,
    megnevezes text NOT NULL UNIQUE,
    kategoria text NOT NULL
);

CREATE TABLE felvetel (
    felvetel_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    beteg_id integer NOT NULL
        REFERENCES beteg (beteg_id) ON DELETE RESTRICT,
    agy_id integer NOT NULL
        REFERENCES agy (agy_id) ON DELETE RESTRICT,
    felvevo_orvos_id integer NOT NULL
        REFERENCES orvos (alkalmazott_id) ON DELETE RESTRICT,
    felvetel_idopont timestamptz NOT NULL,
    elbocsatas_idopont timestamptz,
    statusz text NOT NULL DEFAULT 'aktiv'
        CHECK (statusz IN ('aktiv', 'lezart', 'atorott')),
    megjegyzes text,
    CONSTRAINT ck_felvetel_statusz_ido CHECK (
        (statusz = 'aktiv' AND elbocsatas_idopont IS NULL)
        OR (
            statusz IN ('lezart', 'atorott')
            AND elbocsatas_idopont IS NOT NULL
            AND elbocsatas_idopont > felvetel_idopont
        )
    )
);

-- Ugyanaz a beteg és ugyanaz az ágy időben nem fedheti egymást.
-- A nyitott felvétel felső határa a végtelen, ezért két aktív sor mindig ütközik.
ALTER TABLE felvetel
    ADD CONSTRAINT ex_felvetel_beteg_utkozes
    EXCLUDE USING gist (
        beteg_id WITH =,
        tstzrange(felvetel_idopont, COALESCE(elbocsatas_idopont, 'infinity'::timestamptz), '[)') WITH &&
    );

ALTER TABLE felvetel
    ADD CONSTRAINT ex_felvetel_agy_utkozes
    EXCLUDE USING gist (
        agy_id WITH =,
        tstzrange(felvetel_idopont, COALESCE(elbocsatas_idopont, 'infinity'::timestamptz), '[)') WITH &&
    );

CREATE TABLE felvetel_diagnozis (
    felvetel_id integer NOT NULL
        REFERENCES felvetel (felvetel_id) ON DELETE CASCADE,
    diagnozis_kod varchar(8) NOT NULL
        REFERENCES diagnozis (kod) ON UPDATE CASCADE ON DELETE RESTRICT,
    tipus text NOT NULL CHECK (tipus IN ('fo', 'mellek')),
    PRIMARY KEY (felvetel_id, diagnozis_kod)
);

CREATE TABLE vizit (
    vizit_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    beteg_id integer NOT NULL
        REFERENCES beteg (beteg_id) ON DELETE RESTRICT,
    orvos_id integer NOT NULL
        REFERENCES orvos (alkalmazott_id) ON DELETE RESTRICT,
    idopont_kezdet timestamptz NOT NULL,
    idopont_vege timestamptz NOT NULL,
    statusz text NOT NULL DEFAULT 'tervezett'
        CHECK (statusz IN ('tervezett', 'megjelent', 'lemondott', 'nem_jelent_meg')),
    panasz text,
    javaslat text,
    CONSTRAINT ck_vizit_tartam CHECK (
        idopont_vege > idopont_kezdet
        AND idopont_vege <= idopont_kezdet + INTERVAL '4 hours'
    )
);

-- A lemondott és a meg nem jelent rendelés nem foglalja az orvos idejét.
-- A tartomány félig nyílt [kezd, vég), ezért az egymás utáni rendelés megengedett.
ALTER TABLE vizit
    ADD CONSTRAINT ex_vizit_orvos_utkozes
    EXCLUDE USING gist (
        orvos_id WITH =,
        tstzrange(idopont_kezdet, idopont_vege, '[)') WITH &&
    ) WHERE (statusz IN ('tervezett', 'megjelent'));

-- ---------------------------------------------------------------------------
-- Gyógyszer és készletnapló
-- A készlet nem oszlop a gyógyszeren: a mozgások összege a készlet.
-- ---------------------------------------------------------------------------

CREATE TABLE gyogyszer (
    gyogyszer_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nev text NOT NULL,
    hatoanyag text NOT NULL,
    kiszereles text NOT NULL,
    venykoteles boolean NOT NULL DEFAULT true,
    UNIQUE (nev, kiszereles)
);

CREATE TABLE veny (
    veny_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    beteg_id integer NOT NULL
        REFERENCES beteg (beteg_id) ON DELETE RESTRICT,
    orvos_id integer NOT NULL
        REFERENCES orvos (alkalmazott_id) ON DELETE RESTRICT,
    vizit_id integer
        REFERENCES vizit (vizit_id) ON DELETE RESTRICT,
    felvetel_id integer
        REFERENCES felvetel (felvetel_id) ON DELETE RESTRICT,
    kiallitas_datuma date NOT NULL DEFAULT CURRENT_DATE,
    megjegyzes text,
    CONSTRAINT ck_veny_kapcsolat CHECK (num_nonnulls(vizit_id, felvetel_id) = 1)
);

CREATE TABLE veny_tetel (
    veny_tetel_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    veny_id integer NOT NULL
        REFERENCES veny (veny_id) ON DELETE CASCADE,
    gyogyszer_id integer NOT NULL
        REFERENCES gyogyszer (gyogyszer_id) ON DELETE RESTRICT,
    mennyiseg integer NOT NULL CHECK (mennyiseg > 0),
    adag text NOT NULL,
    gyakorisag text NOT NULL,
    kiadva boolean NOT NULL DEFAULT false
);

CREATE TABLE keszlet_mozgas (
    mozgas_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gyogyszer_id integer NOT NULL
        REFERENCES gyogyszer (gyogyszer_id) ON DELETE RESTRICT,
    mennyiseg integer NOT NULL CHECK (mennyiseg <> 0),
    ok text NOT NULL CHECK (ok IN ('bevetel', 'kiadas', 'korrekcio', 'selejt')),
    veny_tetel_id integer
        REFERENCES veny_tetel (veny_tetel_id) ON DELETE RESTRICT,
    ido timestamptz NOT NULL DEFAULT now(),
    megjegyzes text,
    CONSTRAINT ck_keszlet_mozgas_elojel CHECK (
        (ok = 'bevetel' AND mennyiseg > 0 AND veny_tetel_id IS NULL)
        OR (ok = 'kiadas' AND mennyiseg < 0 AND veny_tetel_id IS NOT NULL)
        OR (ok = 'selejt' AND mennyiseg < 0 AND veny_tetel_id IS NULL)
        OR (ok = 'korrekcio' AND mennyiseg <> 0 AND veny_tetel_id IS NULL)
    )
);

