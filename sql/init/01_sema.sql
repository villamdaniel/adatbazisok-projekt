-- ---------------------------------------------------------------------------
-- Pénzügy
-- Az egészségügyi ellátás a mintában áfamentes (0). Az igazolás 27%-os.
-- A tétel neve és ára a kiállítás pillanatának másolata.
-- ---------------------------------------------------------------------------

CREATE TABLE szolgaltatas (
    szolgaltatas_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kod varchar(12) NOT NULL UNIQUE,
    nev text NOT NULL UNIQUE,
    netto_egysegar numeric(12, 2) NOT NULL CHECK (netto_egysegar >= 0),
    afa_kulcs numeric(4, 2) NOT NULL CHECK (afa_kulcs IN (0, 5, 18, 27))
);

CREATE TABLE szamla (
    szamla_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    szamla_szam varchar(20) NOT NULL UNIQUE,
    beteg_id integer NOT NULL
        REFERENCES beteg (beteg_id) ON DELETE RESTRICT,
    kiallitas_datuma date NOT NULL DEFAULT CURRENT_DATE,
    hatarido date NOT NULL,
    statusz text NOT NULL DEFAULT 'nyitott'
        CHECK (statusz IN ('nyitott', 'fizetve', 'sztorno')),
    megjegyzes text,
    CONSTRAINT ck_szamla_hatarido CHECK (hatarido >= kiallitas_datuma)
);

CREATE TABLE szamla_tetel (
    tetel_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    szamla_id integer NOT NULL
        REFERENCES szamla (szamla_id) ON DELETE CASCADE,
    szolgaltatas_id integer NOT NULL
        REFERENCES szolgaltatas (szolgaltatas_id) ON DELETE RESTRICT,
    megnevezes text NOT NULL,
    mennyiseg numeric(8, 2) NOT NULL CHECK (mennyiseg > 0),
    netto_egysegar numeric(12, 2) NOT NULL CHECK (netto_egysegar >= 0),
    afa_kulcs numeric(4, 2) NOT NULL CHECK (afa_kulcs IN (0, 5, 18, 27)),
    brutto_osszeg numeric(14, 2) GENERATED ALWAYS AS (
        round(mennyiseg * netto_egysegar * (1 + afa_kulcs / 100), 2)
    ) STORED
);

CREATE TABLE fizetes (
    fizetes_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    szamla_id integer NOT NULL
        REFERENCES szamla (szamla_id) ON DELETE RESTRICT,
    osszeg numeric(12, 2) NOT NULL CHECK (osszeg > 0),
    fizetes_mod text NOT NULL CHECK (fizetes_mod IN ('keszpenz', 'kartya', 'utalas')),
    idopont timestamptz NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------------
-- Audit. A triggerek töltik, kézzel nem írunk bele a betöltéskor.
