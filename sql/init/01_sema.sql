CREATE EXTENSION IF NOT EXISTS citext;
CREATE EXTENSION IF NOT EXISTS btree_gist;

-- A TAJ 9 számjegy. Az első nyolcat 3,7,3,7,3,7,3,7 súllyal szorozzuk,
-- a kilencedik jegy a súlyozott összeg utolsó számjegye.
CREATE OR REPLACE FUNCTION taj_ervenyes(p_taj text)
RETURNS boolean
LANGUAGE plpgsql
IMMUTABLE
PARALLEL SAFE
AS $$
DECLARE
    v_sum int := 0;
    v_suly int[] := ARRAY[3, 7, 3, 7, 3, 7, 3, 7];
    i int;
BEGIN
    IF p_taj IS NULL OR p_taj !~ '^[0-9]{9}$' THEN
        RETURN false;
    END IF;

    FOR i IN 1..8 LOOP
        v_sum := v_sum + substr(p_taj, i, 1)::int * v_suly[i];
    END LOOP;

    RETURN (v_sum % 10) = substr(p_taj, 9, 1)::int;
END;
$$;

CREATE DOMAIN dom_taj AS varchar(9)
    CONSTRAINT ck_dom_taj CHECK (taj_ervenyes(VALUE));

CREATE DOMAIN dom_email AS citext
    CONSTRAINT ck_dom_email CHECK (VALUE ~ '^[^@\s]+@[^@\s]+\.[^@\s]+$');

-- ---------------------------------------------------------------------------
